import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);

const iconSet = require("@iconify-json/tabler/icons.json");

const ICONS = {
  fire: "flame",
  mechanism: "settings",
  date: "calendar",
  astronomy: "telescope",
  intelligence: "brain",
  computing: "cpu",
  world: "world",
  idea: "bulb",
  maritime: "ship",
  science: "microscope",
  power: "crown",
  time: "clock",
  document: "book",
  location: "map-pin",
  physics: "atom",
  space: "rocket",
  discovery: "search",
  engineering: "tools",
};

const getIconData = (name) => {
  const icon = iconSet.icons?.[name];

  if (!icon) {
    throw new Error(
      `Iconify Tabler icon "${name}" was not found.`
    );
  }

  return {
    body: icon.body,
    width: icon.width ?? iconSet.width ?? 24,
    height: icon.height ?? iconSet.height ?? 24,
  };
};

const registry = Object.fromEntries(
  Object.entries(ICONS).map(([semanticName, iconName]) => [
    semanticName,
    getIconData(iconName),
  ]),
);

const output = `/*
 * AUTO-GENERATED by scripts/generate-icon-registry.mjs
 *
 * Source: @iconify-json/tabler
 *
 * Only CurioMint's approved whitelist is emitted here.
 * No Iconify API call is made during Remotion rendering.
 */
import type { IconCalloutIcon } from "./types";

export interface LocalIconData {
  body: string;
  width: number;
  height: number;
}

export const LOCAL_ICON_REGISTRY = ${JSON.stringify(
  registry,
  null,
  2,
)} as const satisfies Record<IconCalloutIcon, LocalIconData>;
`;

const currentFile = fileURLToPath(import.meta.url);
const repoRoot = path.resolve(path.dirname(currentFile), "..");

const outputPath = path.join(
  repoRoot,
  "src",
  "templates",
  "curiomint-documentary",
  "icon-callouts",
  "iconRegistry.generated.ts",
);

fs.writeFileSync(outputPath, output, "utf8");

console.log(
  `Generated ${Object.keys(registry).length} local Iconify icons -> ${outputPath}`,
);